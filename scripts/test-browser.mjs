import assert from 'node:assert/strict'
import { readFile,mkdir,writeFile } from 'node:fs/promises'
import { chromium } from '@playwright/test'
import { transaction,pool } from '../server/db.mjs'

const base=process.env.TEST_BASE_URL || 'http://127.0.0.1:5173'
const account=JSON.parse(await readFile('.private/qa-account.json','utf8'))
await mkdir('.private/screenshots',{recursive:true})
const browser=await chromium.launch({headless:true})
const errors=[]
const context=await browser.newContext({viewport:{width:1440,height:1000}})
const page=await context.newPage()
page.on('pageerror',error=>errors.push(error.message))
let createdCustomer
let openedCash=false
try{
  await page.goto(base)
  await page.getByRole('heading',{name:'Como podemos te atender?'}).waitFor()
  assert.equal(await page.getByRole('link',{name:/WhatsApp Fale/}).getAttribute('href'),'https://wa.me/554588186553')
  await page.screenshot({animations:'disabled',path:'.private/screenshots/site-desktop.png',fullPage:true})
  await page.getByRole('link',{name:/Agendamento Reserve/}).click()
  await page.getByRole('heading',{name:'Escolha seu serviço'}).waitFor()
  const catalog=await (await page.request.get(`${base}/api/catalog`)).json()
  const service=catalog.data.services.find(row=>row.price_cents>0)
  const professional=catalog.data.professionals.find(row=>row.default_commission_percent>0)??catalog.data.professionals[0]
  await page.locator('.service-options button').filter({hasText:service.name}).click()
  await page.getByRole('button',{name:'Continuar',exact:true}).click()
  const professionalCard=page.locator('.professional-card').filter({hasText:professional.name})
  const photo=await professionalCard.locator('img,.professional-photo-placeholder').boundingBox()
  assert.ok(photo && Math.abs(photo.width/photo.height-0.8)<0.02,'Foto do profissional fora da proporção 4:5')
  await page.screenshot({animations:'disabled',path:'.private/screenshots/profissionais-desktop-v1.20.png',fullPage:true})
  await professionalCard.click()
  await page.getByRole('button',{name:'Continuar',exact:true}).click()
  const day=new Date();day.setDate(day.getDate()+1)
  if(day.getDay()===0)day.setDate(day.getDate()+1)
  const date=day.toLocaleDateString('en-CA',{timeZone:'America/Sao_Paulo'})
  await page.getByLabel('Escolha uma data').fill(date,{force:true})
  await page.locator('.slots button:not([disabled])').first().waitFor()
  const centerCheck=async()=>{
    const boxes=await Promise.all(['.booking-slot-head','.booking-calendar-control','.booking-date','.slots'].map(selector=>page.locator(selector).boundingBox()))
    const centers=boxes.map(box=>{assert.ok(box);return box.x+box.width/2})
    assert.ok(Math.max(...centers)-Math.min(...centers)<5,'Escolha do horário desalinhada')
    assert.equal(await page.getByRole('button',{name:'Atualizar',exact:true}).count(),0)
    assert.equal(await page.locator('.booking-slot-head').evaluate(el=>globalThis.getComputedStyle(el).textAlign),'center')
  }
  await centerCheck()
  await page.screenshot({animations:'disabled',path:'.private/screenshots/horarios-desktop-v1.20.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await centerCheck()
  await page.screenshot({animations:'disabled',path:'.private/screenshots/horarios-mobile-v1.20.png',fullPage:true})
  await page.setViewportSize({width:1440,height:1000})
  const chosenTime=await page.locator('.slots button:not([disabled])').first().locator('span').innerText()
  await page.locator('.slots button:not([disabled])').first().click()
  await page.getByRole('button',{name:'Continuar',exact:true}).click()
  await page.getByLabel('Nome completo').fill('QA Entrega Machado')
  await page.getByLabel('WhatsApp',{exact:true}).fill('4500000000')
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:'Confirmar agendamento',exact:true}).click()
  await page.getByRole('heading',{name:'Até breve!'}).waitFor()
  await page.screenshot({animations:'disabled',path:'.private/screenshots/site-confirmacao.png',fullPage:true})
  createdCustomer=(await pool.query("select id from customers where name='QA Entrega Machado' and phone='4500000000'")).rows[0]?.id
  assert.ok(createdCustomer)
  await page.goto(`${base}/admin`)
  await page.getByLabel('E-mail',{exact:true}).fill(account.email)
  await page.getByLabel('Senha',{exact:true}).fill(account.password)
  await page.getByRole('button',{name:'Entrar',exact:true}).click()
  await page.getByRole('heading',{name:'Agenda',exact:true}).waitFor()
  assert.equal(await page.locator('.mobile-nav,.mobile-create,.agenda-professionals').count(),0)
  await page.getByRole('button',{name:'Filtros',exact:true}).click()
  await page.getByLabel('Data',{exact:true}).fill(date)
  await page.getByLabel('Profissional',{exact:true}).selectOption(professional.id)
  await page.getByLabel('Cliente ou telefone').fill('QA Entrega')
  await page.getByLabel('Serviço ou agendamento').fill(service.name)
  await page.getByRole('button',{name:'Aplicar filtros'}).click()
  const agendaCard=page.getByRole('article',{name:'Agendamento de QA Entrega Machado',exact:true})
  await agendaCard.waitFor()
  for(const text of [professional.name,service.name,chosenTime,'Aguardando presença'])assert.ok((await agendaCard.innerText()).includes(text))
  await page.screenshot({animations:'disabled',path:'.private/screenshots/agenda-desktop-v1.20.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  assert.ok(await page.getByRole('button',{name:'Abrir menu',exact:true}).isVisible())
  assert.equal(await page.evaluate(()=>globalThis.document.documentElement.scrollWidth>globalThis.innerWidth),false)
  await page.screenshot({animations:'disabled',path:'.private/screenshots/agenda-mobile-v1.20.png',fullPage:true})
  await page.locator('.agenda-availability summary').click()
  assert.ok(await page.getByRole('button',{name:`${chosenTime} Ocupado`,exact:true}).isDisabled())
  await agendaCard.getByRole('button',{name:'Confirmar que veio',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Confirmar',exact:true}).click()
  await agendaCard.getByText('Veio · pronto para receber',{exact:true}).waitFor()
  await page.getByRole('button',{name:/^Filtros/}).click()
  await page.getByLabel('Consultar',{exact:true}).selectOption('period')
  await page.getByLabel('Data inicial',{exact:true}).fill(date)
  await page.getByLabel('Data final',{exact:true}).fill(date)
  await page.getByLabel('Situação do atendimento',{exact:true}).selectOption('paid')
  await page.getByRole('button',{name:'Aplicar filtros'}).click()
  assert.equal(await agendaCard.count(),0,'Filtro de pago deve excluir atendimento ainda não recebido')
  await page.getByRole('button',{name:/^Filtros/}).click()
  await page.getByLabel('Consultar',{exact:true}).selectOption('day')
  await page.getByLabel('Situação do atendimento',{exact:true}).selectOption('')
  const appointmentId=(await pool.query('select id from appointments where customer_id=$1',[createdCustomer])).rows[0].id
  await page.getByLabel('Serviço ou agendamento').fill(appointmentId)
  await page.getByRole('button',{name:'Aplicar filtros'}).click()
  await agendaCard.waitFor()
  await page.getByRole('button',{name:/^Filtros/}).click()
  await page.getByLabel('Serviço ou agendamento').fill(service.name)
  await page.getByRole('button',{name:'Aplicar filtros'}).click()
  const rpc=async(name,params={})=>{
    const response=await page.request.post(`${base}/api/rpc`,{headers:{origin:new URL(base).origin},data:{name,params}})
    assert.equal(response.status(),200)
    const result=await response.json();assert.equal(result.error,null);return result.data
  }
  const slots=await rpc('public_booking_slots',{chosen_service:service.id,booking_day:date,preferred_professional:professional.id})
  assert.equal(slots.find(slot=>String(slot.slot_time).slice(0,5)===chosenTime)?.available,false,'Reserva deve bloquear o horário público')
  const absentTime=String(slots.find(slot=>slot.available).slot_time).slice(0,5)
  const absence=await rpc('office_action',{action:'create_appointment',payload:{name:'QA Entrega Machado',phone:'4500000000',professional_id:professional.id,service_id:service.id,starts_at:`${date}T${absentTime}:00-03:00`}})
  await page.getByRole('button',{name:'Atualizar',exact:true}).click()
  const absentCard=page.locator(`[data-appointment-id="${absence.id}"]`)
  await absentCard.getByRole('button',{name:'Confirmar que não veio',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Confirmar',exact:true}).click()
  await absentCard.getByText('Não veio',{exact:true}).waitFor()
  await absentCard.getByRole('button',{name:'Remover QA Entrega Machado da agenda',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Remover da Agenda',exact:true}).click()
  await absentCard.waitFor({state:'detached'})
  const released=await rpc('public_booking_slots',{chosen_service:service.id,booking_day:date,preferred_professional:professional.id})
  assert.equal(released.find(slot=>String(slot.slot_time).slice(0,5)===absentTime)?.available,true)
  const pendingPayment=await pool.query('select p.id from payments p join commands c on c.id=p.command_id where c.customer_id=$1',[createdCustomer])
  assert.equal(pendingPayment.rows.length,0,'Presença não pode registrar pagamento antes de receber')
  await page.setViewportSize({width:1440,height:1000})
  await page.goto(`${base}/admin/clientes`)
  await page.getByText('QA Entrega Machado',{exact:true}).first().waitFor()
  await page.goto(`${base}/admin/caixa`)
  await page.getByRole('heading',{name:'Caixa',exact:true}).waitFor()
  if(await page.getByRole('button',{name:'Abrir caixa',exact:true}).count()){
    await page.getByRole('button',{name:'Abrir caixa',exact:true}).click()
    await page.getByLabel('Dinheiro inicial (R$)').fill('100')
    await page.getByRole('button',{name:'Confirmar',exact:true}).click()
    openedCash=true
  }
  await page.getByRole('button',{name:'Fechar caixa',exact:true}).waitFor()
  const ready=page.locator('.ready-command-card, .cash-command-card, .record-row').filter({hasText:'QA Entrega Machado'})
  if(await ready.count())await ready.first().getByRole('button',{name:'Receber',exact:true}).click()
  else await page.getByRole('button',{name:'Receber',exact:true}).first().click()
  const dialog=page.getByRole('dialog')
  await dialog.getByRole('button',{name:'Pix',exact:true}).click()
  await page.getByRole('button',{name:'Pagamento recebido',exact:true}).click()
  if(openedCash){
    await page.getByRole('button',{name:'Fechar caixa',exact:true}).click()
    await page.getByLabel('Dinheiro contado no fechamento (R$)').fill('100')
    await page.getByRole('button',{name:'Confirmar',exact:true}).click()
    await page.getByRole('button',{name:'Abrir caixa',exact:true}).waitFor()
  }
  const check=await pool.query('select p.amount_cents,p.method,a.status from payments p join commands c on c.id=p.command_id join appointments a on a.id=c.appointment_id where c.customer_id=$1',[createdCustomer])
  assert.equal(check.rows.length,1);assert.equal(check.rows[0].method,'pix');assert.equal(check.rows[0].status,'completed');assert.equal(check.rows[0].amount_cents,service.price_cents)
  await page.goto(`${base}/admin/agenda`)
  await page.getByRole('button',{name:'Filtros',exact:true}).click()
  await page.getByLabel('Data',{exact:true}).fill(date)
  await page.getByLabel('Cliente ou telefone').fill('QA Entrega')
  await page.getByLabel('Situação do atendimento',{exact:true}).selectOption('paid')
  await page.getByRole('button',{name:'Aplicar filtros'}).click()
  await agendaCard.getByText('Pago',{exact:true}).waitFor()
  await agendaCard.getByRole('button',{name:'Remover QA Entrega Machado da agenda',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Remover da Agenda',exact:true}).click()
  await agendaCard.waitFor({state:'detached'})
  assert.equal(Number((await pool.query('select count(*) as n from payments p join commands c on c.id=p.command_id where c.customer_id=$1',[createdCustomer])).rows[0].n),1,'Remover da Agenda apagou pagamento')
  await page.goto(`${base}/admin/configuracoes`)
  await page.getByRole('heading',{name:'Cópias de segurança'}).waitFor()
  await page.screenshot({animations:'disabled',path:'.private/screenshots/painel-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.goto(`${base}/admin/agenda`)
  await page.locator('.page').waitFor()
  await page.screenshot({animations:'disabled',path:'.private/screenshots/painel-mobile.png',fullPage:true})
  await context.setOffline(true)
  await page.getByRole('status').filter({hasText:'Sem internet.'}).waitFor()
  await context.setOffline(false)
  await page.goto(`${base}/privacidade`)
  await page.getByRole('heading',{name:'Privacidade',exact:true}).waitFor()
  assert.deepEqual(errors,[])
  const commission=(await pool.query("select coalesce(sum(i.commission_cents),0) as amount from command_items i join commands c on c.id=i.command_id where c.customer_id=$1 and c.status='closed'",[createdCustomer])).rows[0]
  const rule=(await pool.query('select commission_percent from professional_services where professional_id=$1 and service_id=$2',[professional.id,service.id])).rows[0]
  assert.equal(Number(commission.amount),Math.round(service.price_cents*Number(rule?.commission_percent??professional.default_commission_percent)/100))
  console.log('PASS navegador: fotos 4:5, horários centralizados desktop/mobile, reserva pública, filtros completos, agenda sem menu inferior, presença → Caixa sem Comandas, pagamento Pix e comissão correta.')
}catch(error){await page.screenshot({animations:'disabled',path:'.private/screenshots/falha.png',fullPage:true});throw error}finally{
  await browser.close()
  await transaction(account.id,async client=>{
    const customer=(await client.query("select id from customers where name='QA Entrega Machado' and phone='4500000000'")).rows[0]
    if(customer){
      const commands=(await client.query('select id from commands where customer_id=$1',[customer.id])).rows
      for(const command of commands)await client.query('select delete_command_record($1)',[command.id])
      await client.query('select delete_customer_record($1)',[customer.id])
    }
    await client.query("delete from cash_sessions where opened_by=$1 and not exists(select 1 from cash_movements m where m.session_id=cash_sessions.id)",[account.id])
    await client.query("delete from notifications where body like 'QA Entrega Machado agendou%' ")
  })
  await writeFile('.private/browser-verification.json',JSON.stringify({date:new Date().toISOString(),errors,base},null,2))
  await pool.end()
}
