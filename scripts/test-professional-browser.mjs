/* global document, window, getComputedStyle */
import assert from 'node:assert/strict'
import { readFile,mkdir,writeFile } from 'node:fs/promises'
import { chromium,webkit,devices } from '@playwright/test'

const base=process.env.TEST_BASE_URL||'http://127.0.0.1:5173'
const accounts=JSON.parse(await readFile('.private/professional-delivery.json','utf8'))
const account=accounts.find(value=>value.password)
assert.ok(account,'Prepare as contas dos profissionais antes da verificação.')
await mkdir('.private/screenshots',{recursive:true})
const cases=[{name:'professional-android-web',engine:chromium,options:{viewport:{width:390,height:844},deviceScaleFactor:1}},{name:'professional-iphone',engine:webkit,options:devices['iPhone 13']},{name:'professional-pc',engine:chromium,options:{viewport:{width:1440,height:1000}}}]
